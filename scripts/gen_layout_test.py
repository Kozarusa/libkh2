"""Generates crates/libkh2/tests/layout.rs from include/kh2.h: for every `typedef struct` of the
header, the Rust test prints a C file asserting `sizeof` and every field's `offsetof` equal to the
Rust `#[repr(C)]` struct's (`size_of`, `offset_of!`), and compiles it with the platform's C compiler
(MSVC through vcvars64.bat on Windows, `cc` elsewhere). Run after changing a struct in kh2.h.

    python scripts/gen_layout_test.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
src = (ROOT / 'include' / 'kh2.h').read_text(encoding='utf-8')
src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)

structs = []
for m in re.finditer(r'typedef struct (\w+)\s*\{(.*?)\}\s*(\w+)\s*;', src, re.S):
    name, body = m.group(3), m.group(2)
    fields = []
    for decl in body.split(';'):
        decl = decl.strip()
        if not decl:
            continue
        parts = decl.split(None, 1)
        if len(parts) < 2:
            continue
        for f in parts[1].split(','):
            f = f.strip()
            fname = re.match(r'(\w+)', f).group(1)
            fields.append(fname)
    structs.append((name, fields))


def rust_name(c):
    base = c[len('kh2_'):] if c.startswith('kh2_') else c
    base = base[:-2] if base.endswith('_t') else base
    if base == 'surface':
        return 'Surface'
    if base == 'motion_desc':
        return 'Kh2MotionInfo'
    if base == 'inputs':
        return 'Kh2Inputs'
    return 'Kh2' + ''.join(p.capitalize() for p in base.split('_'))


lines = []
lines.append('//! Generated by `scripts/gen_layout_test.py` from include/kh2.h: the C structs of the header and')
lines.append('//! the Rust `#[repr(C)]` structs of the library have the same size and field offsets, checked by a C')
lines.append('//! compiler (`static_assert` over `sizeof` / `offsetof`). Skipped (with a note) when no compiler is found.')
lines.append('')
lines.append('use std::mem::{offset_of, size_of};')
lines.append('')
lines.append('use kh2::ffi::*;')
lines.append('use kh2::Surface;')
lines.append('')
lines.append('fn asserts() -> String {')
lines.append('    let mut c = String::from("#include <stddef.h>\\n#include <assert.h>\\n#include \\"kh2.h\\"\\n");')
for name, fields in structs:
    r = rust_name(name)
    lines.append(f'    c += &format!("static_assert(sizeof({name}) == {{}}, \\"{name} size\\");\\n", size_of::<{r}>());')
    for f in fields:
        rf = '_pad' if f == '_pad' else f
        lines.append(f'    c += &format!("static_assert(offsetof({name}, {f}) == {{}}, \\"{name}.{f}\\");\\n", offset_of!({r}, {rf}));')
lines.append('    c += "int main(void) { return 0; }\\n";')
lines.append('    c')
lines.append('}')
lines.append('')
lines.append('''#[test]
fn c_layouts_match_kh2_h() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let dir = std::env::temp_dir().join("libkh2_layout");
    std::fs::create_dir_all(&dir).unwrap();
    let file = dir.join("layout.c");
    std::fs::write(&file, asserts()).unwrap();
    let include = root.join("include");
    let out = if cfg!(windows) {
        let vcvars = ["C:/Program Files (x86)/Microsoft Visual Studio", "C:/Program Files/Microsoft Visual Studio"]
            .iter()
            .flat_map(|b| std::fs::read_dir(b).into_iter().flatten().flatten())
            .flat_map(|v| std::fs::read_dir(v.path()).into_iter().flatten().flatten())
            .map(|e| e.path().join("VC/Auxiliary/Build/vcvars64.bat"))
            .find(|p| p.exists());
        let Some(vcvars) = vcvars else {
            eprintln!("no MSVC found: layout check skipped");
            return;
        };
        let bat = dir.join("layout.bat");
        let script = format!("@call \\"{}\\" >nul\\r\\n@cl /nologo /std:c11 /c /I \\"{}\\" \\"{}\\" /Fo\\"{}\\\\layout.obj\\"\\r\\n", vcvars.display(), include.display(), file.display(), dir.display());
        std::fs::write(&bat, script).unwrap();
        std::process::Command::new("cmd").arg("/C").arg(&bat).output()
    } else {
        std::process::Command::new("cc").args(["-std=c11", "-c", "-I"]).arg(&include).arg(&file).arg("-o").arg(dir.join("layout.o")).output()
    };
    let Ok(out) = out else {
        eprintln!("no C compiler: layout check skipped");
        return;
    };
    let text = format!("{}{}", String::from_utf8_lossy(&out.stdout), String::from_utf8_lossy(&out.stderr));
    assert!(out.status.success(), "the C layout check failed:\\n{text}");
    eprintln!("C layout check passed ({} bytes of asserts)", asserts().len());
}''')
(ROOT / 'crates' / 'libkh2' / 'tests' / 'layout.rs').write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
print(f'{len(structs)} structs, {sum(len(f) for _, f in structs)} fields')
